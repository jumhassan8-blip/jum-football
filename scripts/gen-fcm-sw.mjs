// Generates public/firebase-messaging-sw.js from .env.local.
// The FCM service worker must live at the site root and can't read
// NEXT_PUBLIC_* at runtime — so we bake the (public) config at build.
// Without Firebase config the SW is still emitted in a safe stub mode
// (registers but no-ops); the client only asks for it after keys verify.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const envFile = join(ROOT, ".env.local");
const cfg = {};
try {
  const text = readFileSync(envFile, "utf8");
  for (const line of text.split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !m[1].startsWith("#")) cfg[m[1]] = m[2];
  }
} catch {
  /* no .env.local — stub mode */
}

const firebaseConfig = {
  apiKey: cfg.NEXT_PUBLIC_FB_FOOTBALL_API_KEY ?? "",
  authDomain: cfg.NEXT_PUBLIC_FB_FOOTBALL_AUTH_DOMAIN ?? "",
  projectId: cfg.NEXT_PUBLIC_FB_FOOTBALL_PROJECT_ID ?? "",
  storageBucket: cfg.NEXT_PUBLIC_FB_FOOTBALL_STORAGE_BUCKET ?? "",
  messagingSenderId: cfg.NEXT_PUBLIC_FB_FOOTBALL_MESSAGING_SENDER_ID ?? "",
  appId: cfg.NEXT_PUBLIC_FB_FOOTBALL_APP_ID ?? "",
};

const FCM_VERSION = "10.14.1";
const configured = !!(firebaseConfig.apiKey && firebaseConfig.projectId);

const sw = `// GENERATED by scripts/gen-fcm-sw.mjs — do not edit by hand.
// JUM Football FCM service worker (public config baked at build).
importScripts("https://www.gstatic.com/firebasejs/${FCM_VERSION}/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/${FCM_VERSION}/firebase-messaging-compat.js");

const CONFIGURED = ${configured};
if (CONFIGURED) {
  firebase.initializeApp(${JSON.stringify(firebaseConfig)});
  const messaging = firebase.messaging();

  // Background messages → system notification. Falls back to a raw push
  // payload when the FCM envelope is absent.
  messaging.onBackgroundMessage((payload) => {
    const n = payload.notification || {};
    const d = payload.data || {};
    const title = n.title || d.title || "JUM Football";
    const body = n.body || d.body || "";
    const url = d.url || "/";
    return self.registration.showNotification(title, {
      body,
      icon: "/favicon.ico",
      badge: "/favicon.ico",
      data: { url },
    });
  });
}

self.addEventListener("push", (event) => {
  if (CONFIGURED) return; // firebase compat already showed it
  let title = "JUM Football";
  let body = "";
  let url = "/";
  try {
    const p = event.data ? event.data.json() : {};
    title = p.notification?.title || p.data?.title || title;
    body = p.notification?.body || p.data?.body || "";
    url = p.data?.url || "/";
  } catch { /* keep defaults */ }
  event.waitUntil(
    self.registration.showNotification(title, { body, icon: "/favicon.ico", data: { url } })
  );
});

// Tap → focus an open tab on the match, else open a new one.
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = (event.notification.data && event.notification.data.url) || "/";
  event.waitUntil(
    clients.matchAll({ type: "window", includeUncontrolled: true }).then((list) => {
      for (const c of list) {
        if (c.url && c.url.includes(url)) return c.focus();
      }
      return clients.openWindow(url);
    })
  );
});
`;

writeFileSync(join(ROOT, "public", "firebase-messaging-sw.js"), sw);
console.log(
  configured
    ? "[fcm-sw] firebase-messaging-sw.js generated with project config"
    : "[fcm-sw] firebase-messaging-sw.js generated in stub mode (no Firebase config)"
);
